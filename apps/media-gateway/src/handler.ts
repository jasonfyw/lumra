import type { MediaTokenKeyring } from '@lumra/config';
import {
  queueMessageSchema,
  type DeliveryServedMessage,
  type MediaTokenClaims,
  type QueueMessage,
} from '@lumra/contracts';
import { sanitizeDownloadFilename } from '@lumra/domain';
import { archivePartKey, derivativeKey, originalKey } from '@lumra/media';
import {
  AccessStateUnavailableError,
  evaluateGalleryAccess,
  verifyMediaToken,
  type GalleryAccessStore,
} from '@lumra/tokens';
import {
  contentDisposition,
  corsHeaders,
  ifNoneMatchHits,
  ifRangeAllows,
  parseRange,
  type ByteRange,
} from './http';

export interface GatewayDeps {
  keyring: MediaTokenKeyring;
  accessStore: GalleryAccessStore;
  buckets: { originals: R2Bucket; derivatives: R2Bucket; archives: R2Bucket };
  usage: Queue<QueueMessage>;
  allowedOrigins: readonly string[];
  now: () => Date;
  waitUntil: (promise: Promise<unknown>) => void;
  log: (level: 'info' | 'warn' | 'error', msg: string, fields?: Record<string, unknown>) => void;
}

/** `/m/{header}.{payload}.{signature}` — token in the path, never in cookies or query. */
const MEDIA_PATH = /^\/m\/([A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+)$/;

const PREVIEW_CACHE = 'private, max-age=300';
const DOWNLOAD_CACHE = 'private, no-store';

const ERROR_TEXT: Record<number, string> = {
  401: 'Unauthorized',
  403: 'Forbidden',
  404: 'Not Found',
  416: 'Range Not Satisfiable',
  503: 'Service Unavailable',
};

interface RequestContext {
  request: Request;
  deps: GatewayDeps;
  requestId: string;
}

function baseHeaders(ctx: RequestContext): Headers {
  const headers = corsHeaders(ctx.request.headers.get('Origin'), ctx.deps.allowedOrigins);
  headers.set('X-Content-Type-Options', 'nosniff');
  headers.set('Referrer-Policy', 'no-referrer');
  headers.set('Content-Security-Policy', "default-src 'none'; sandbox");
  headers.set('Cross-Origin-Resource-Policy', 'cross-origin');
  return headers;
}

/** Generic failure: no internal detail in the body, never cacheable. */
function deny(ctx: RequestContext, status: number, reason: string, extra?: HeadersInit): Response {
  ctx.deps.log(status >= 500 ? 'error' : 'info', 'media request denied', {
    requestId: ctx.requestId,
    status,
    reason,
  });
  const headers = baseHeaders(ctx);
  headers.set('Cache-Control', 'no-store');
  headers.set('Content-Type', 'text/plain; charset=utf-8');
  for (const [k, v] of new Headers(extra)) headers.set(k, v);
  return new Response(ctx.request.method === 'HEAD' ? null : (ERROR_TEXT[status] ?? 'Error'), {
    status,
    headers,
  });
}

interface ResolvedObject {
  bucket: R2Bucket;
  key: string;
}

function resolveObject(claims: MediaTokenClaims, buckets: GatewayDeps['buckets']): ResolvedObject {
  switch (claims.action) {
    case 'preview':
      return {
        bucket: buckets.derivatives,
        key: derivativeKey(claims.gallery_id, claims.media_id, claims.variant_hash),
      };
    case 'original':
      return {
        bucket: buckets.originals,
        key: originalKey(claims.owner_ref, claims.gallery_id, claims.media_id),
      };
    case 'archive':
      return {
        bucket: buckets.archives,
        key: archivePartKey(claims.gallery_id, claims.archive_job_id, claims.archive_part_no),
      };
  }
}

function contentHeaders(ctx: RequestContext, claims: MediaTokenClaims, object: R2Object): Headers {
  const headers = baseHeaders(ctx);
  const storedType = object.httpMetadata?.contentType ?? '';
  headers.set('ETag', object.httpEtag);
  headers.set('Last-Modified', object.uploaded.toUTCString());
  headers.set('Accept-Ranges', 'bytes');

  if (claims.action === 'preview') {
    // Derivatives are generated by us; anything non-image is served as opaque bytes.
    headers.set(
      'Content-Type',
      storedType.startsWith('image/') ? storedType : 'application/octet-stream',
    );
    headers.set('Content-Disposition', contentDisposition('inline'));
    headers.set('Cache-Control', PREVIEW_CACHE);
  } else {
    headers.set('Content-Type', storedType || 'application/octet-stream');
    const filename =
      claims.action === 'original'
        ? sanitizeDownloadFilename(claims.filename, 'photo')
        : ensureZip(
            sanitizeDownloadFilename(
              claims.filename,
              `lumra-archive-part-${claims.archive_part_no}`,
            ),
          );
    headers.set('Content-Disposition', contentDisposition('attachment', filename));
    headers.set('Cache-Control', DOWNLOAD_CACHE);
  }
  return headers;
}

const ensureZip = (name: string) => (/\.zip$/i.test(name) ? name : `${name}.zip`);

function emitUsage(
  ctx: RequestContext,
  claims: MediaTokenClaims,
  range: ByteRange,
  servedAt: Date,
): void {
  const bytes = range.end - range.start + 1;
  if (bytes <= 0) return;
  const parsed = queueMessageSchema.safeParse({
    type: 'delivery.served',
    galleryId: claims.gallery_id,
    action: claims.action,
    mediaId: claims.action === 'archive' ? null : claims.media_id,
    archivePartId: claims.action === 'archive' ? claims.archive_part_id : null,
    variant: claims.action === 'archive' ? null : claims.variant,
    bytes,
    servedAt: servedAt.toISOString(),
    traceId: ctx.requestId,
    dedupeKey: `${claims.jti}:${range.start}-${range.end}`,
  } satisfies DeliveryServedMessage);
  if (!parsed.success) {
    ctx.deps.log('error', 'invalid usage event', { requestId: ctx.requestId });
    return;
  }
  ctx.deps.waitUntil(
    ctx.deps.usage.send(parsed.data).catch((error: unknown) => {
      // Delivery already happened; reconciliation (T27/T13) covers lost events.
      ctx.deps.log('error', 'usage event send failed', {
        requestId: ctx.requestId,
        error: error instanceof Error ? error.name : 'unknown',
      });
    }),
  );
}

/** Handles `GET|HEAD /m/:token`. Authorization always completes before any R2 read. */
export async function handleMediaRequest(
  request: Request,
  deps: GatewayDeps,
  requestId: string,
): Promise<Response> {
  const ctx: RequestContext = { request, deps, requestId };
  const url = new URL(request.url);
  const match = MEDIA_PATH.exec(url.pathname);
  if (!match) return deny(ctx, 401, 'missing_token');

  const now = deps.now();
  const verified = await verifyMediaToken(match[1] as string, deps.keyring, { now });
  if (verified.status !== 'ok') return deny(ctx, 401, `token_${verified.status}`);
  const { claims } = verified;

  let state;
  try {
    state = await deps.accessStore.get(claims.gallery_id);
  } catch (error) {
    // Fail closed: without authoritative state nothing is served.
    const reason =
      error instanceof AccessStateUnavailableError
        ? 'access_state_unavailable'
        : 'access_state_error';
    return deny(ctx, 503, reason, { 'Retry-After': '5' });
  }
  const decision = evaluateGalleryAccess(state, claims.access_version, now);
  if (decision === 'not_found') return deny(ctx, 404, 'gallery_not_found');
  if (decision !== 'allow') return deny(ctx, 403, `gallery_${decision}`);

  let target: ResolvedObject;
  try {
    target = resolveObject(claims, deps.buckets);
  } catch {
    return deny(ctx, 404, 'invalid_key');
  }

  const ifNoneMatch = request.headers.get('If-None-Match');
  const rangeHeader = request.method === 'GET' ? request.headers.get('Range') : null;

  // Fast path: unconditional full GET is a single R2 operation.
  if (request.method === 'GET' && !ifNoneMatch && !rangeHeader) {
    const object = await target.bucket.get(target.key);
    if (!object || !('body' in object)) return deny(ctx, 404, 'object_missing');
    const headers = contentHeaders(ctx, claims, object);
    headers.set('Content-Length', String(object.size));
    if (object.size > 0) emitUsage(ctx, claims, { start: 0, end: object.size - 1 }, now);
    return new Response(object.body, { status: 200, headers });
  }

  const meta = await target.bucket.head(target.key);
  if (!meta) return deny(ctx, 404, 'object_missing');
  const headers = contentHeaders(ctx, claims, meta);

  if (ifNoneMatchHits(ifNoneMatch, meta.httpEtag)) {
    for (const name of ['Content-Type', 'Content-Disposition']) headers.delete(name);
    return new Response(null, { status: 304, headers });
  }

  if (request.method === 'HEAD') {
    headers.set('Content-Length', String(meta.size));
    return new Response(null, { status: 200, headers });
  }

  const range = ifRangeAllows(request.headers.get('If-Range'), meta.httpEtag)
    ? parseRange(rangeHeader, meta.size)
    : null;
  if (range === 'unsatisfiable') {
    return deny(ctx, 416, 'range_unsatisfiable', { 'Content-Range': `bytes */${meta.size}` });
  }

  // Pin the read to the validated ETag so the bytes match the headers above.
  const object = await target.bucket.get(target.key, {
    onlyIf: { etagMatches: meta.etag },
    ...(range ? { range: { offset: range.start, length: range.end - range.start + 1 } } : {}),
  });
  if (!object || !('body' in object)) return deny(ctx, 404, 'object_changed');

  if (range) {
    headers.set('Content-Range', `bytes ${range.start}-${range.end}/${meta.size}`);
    headers.set('Content-Length', String(range.end - range.start + 1));
    emitUsage(ctx, claims, range, now);
    return new Response(object.body, { status: 206, headers });
  }
  headers.set('Content-Length', String(meta.size));
  if (meta.size > 0) emitUsage(ctx, claims, { start: 0, end: meta.size - 1 }, now);
  return new Response(object.body, { status: 200, headers });
}
